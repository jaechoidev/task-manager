//! Documents generated from the state database and the run files: the day's
//! handoff, and the pull request that promotes the integration branch.
//!
//! Nothing here calls an LLM. A handoff repeats what was recorded, including
//! the summaries the summary module wrote when each pull request was opened.

use super::state::{IssueRow, Store};
use super::{first_line, git, github, lock, repo_name, util, Summary};
use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};

pub struct HandoffOptions {
    /// `YYYY-MM-DD`, in UTC. Today when absent.
    pub date: Option<String>,
    /// Where the files go. The configured folder when absent.
    pub out: Option<PathBuf>,
}

/// One issue of a handoff.
pub struct Entry {
    pub row: IssueRow,
    /// (step, vendor, verdict, seconds, pass)
    pub steps: Vec<(String, Option<String>, String, f64, u32)>,
    pub summary: Option<Summary>,
}

fn result_of(row: &IssueRow) -> &'static str {
    match (row.stage.as_str(), row.status.as_str()) {
        ("merged", _) => "Merged",
        (_, "failed") => "Needs a person",
        (_, "dropped") => "Dropped",
        (_, "open") | (_, "green") => "Pull request open",
        (_, "passed") => "Passed, no pull request",
        (_, "waiting") => "Waiting on a usage limit",
        _ => "Was running",
    }
}

/// The handoff for one repository and one day.
pub fn render(repo: &str, date: &str, entries: &[Entry]) -> String {
    let mut out = format!("# Handoff: {repo}, {date}\n\n");
    out.push_str("Generated by `factory handoff` from the state database and the run files. Don't edit this file: the next export writes it again.\n\n");
    out.push_str("## At a glance\n\n| Issue | Result | Pull request | Passes | Agent and check time |\n| --- | --- | --- | --- | --- |\n");
    for entry in entries {
        let passes = entry.steps.iter().map(|s| s.4).max().unwrap_or(0) + 1;
        let seconds: f64 = entry.steps.iter().map(|s| s.3).sum();
        out.push_str(&format!(
            "| #{} {} | {} | {} | {} | {:.0} s |\n",
            entry.row.number,
            entry.row.title.replace('|', "/"),
            result_of(&entry.row),
            entry.row.pr_url.as_deref().unwrap_or("none"),
            passes,
            seconds
        ));
    }

    out.push_str("\n## Needs a person\n\n");
    let stuck: Vec<&Entry> = entries.iter().filter(|e| e.row.status == "failed").collect();
    if stuck.is_empty() {
        out.push_str("Nothing.\n");
    }
    for entry in stuck {
        let failure = entry.row.failure.clone().unwrap_or_default();
        let (what, judgment) = match failure.split_once("\n\nJudgment: ") {
            Some((what, judgment)) => (what.to_string(), Some(judgment.trim().to_string())),
            None => (failure.clone(), None),
        };
        out.push_str(&format!("- **#{} {}** stopped at `{}`. {}\n", entry.row.number, entry.row.title, entry.row.stage, first_line(&what)));
        if let Some(judgment) = judgment {
            out.push_str(&format!("  - Judgment: {}\n", judgment.replace('\n', " ")));
        }
        out.push_str(&format!("  - `factory retry {}` starts it over. `factory drop {}` takes it off the queue.\n", entry.row.number, entry.row.number));
    }

    out.push_str("\n## To look at\n\n");
    let mut any = false;
    for entry in entries {
        let Some(summary) = &entry.summary else { continue };
        if summary.for_a_human.is_empty() {
            continue;
        }
        any = true;
        out.push_str(&format!("**#{} {}**\n\n", entry.row.number, entry.row.title));
        for item in &summary.for_a_human {
            out.push_str(&format!("- {}\n", item.trim()));
        }
        out.push('\n');
    }
    if !any {
        out.push_str("Nothing was flagged.\n");
    }

    out.push_str("\n## Each issue\n");
    for entry in entries {
        out.push_str(&format!("\n### #{} {}\n\n", entry.row.number, entry.row.title));
        out.push_str(&format!("- Result: {}\n", result_of(&entry.row)));
        if let Some(url) = &entry.row.pr_url {
            out.push_str(&format!("- Pull request: {url}\n"));
        }
        if let Some(sha) = &entry.row.head_sha {
            out.push_str(&format!("- Commit: `{sha}`\n"));
        }
        out.push_str(&format!("- Run: `{}`, last change {}\n", entry.row.run_id, entry.row.updated_at));
        if let Some(summary) = &entry.summary {
            out.push_str(&format!("\n{}\n\n{}\n", summary.what_changed.trim(), summary.how_it_went.trim()));
        }
        out.push_str("\n| Pass | Step | Who | Result | Time |\n| --- | --- | --- | --- | --- |\n");
        for (step, vendor, verdict, seconds, pass) in &entry.steps {
            out.push_str(&format!("| {} | {step} | {} | {verdict} | {seconds:.0} s |\n", pass + 1, vendor.as_deref().unwrap_or("engine")));
        }
    }
    out
}

fn expand(path: &str) -> PathBuf {
    match (path.strip_prefix("~/"), std::env::var_os("HOME")) {
        (Some(rest), Some(home)) => PathBuf::from(home).join(rest),
        _ => PathBuf::from(path),
    }
}

/// Writes one handoff per repository that had activity on the day. Returns
/// the files written.
pub fn export(opts: &HandoffOptions) -> Result<Vec<PathBuf>> {
    let home = util::home()?;
    let store = Store::open(&home)?;
    let date = opts.date.clone().unwrap_or_else(|| util::now().chars().take(10).collect());
    if date.len() != 10 || date.chars().filter(|c| *c == '-').count() != 2 {
        bail!("the date must look like 2026-11-24, and '{date}' does not");
    }
    let config = super::config::Config::load(&home)?;
    let folder = opts.out.clone().or(config.handoffs.as_deref().map(expand)).unwrap_or_else(|| home.join("handoffs"));

    let rows: Vec<IssueRow> = store.issues()?.into_iter().filter(|row| row.updated_at.starts_with(&date)).collect();
    let mut repos: Vec<String> = rows.iter().map(|r| r.repo.clone()).collect();
    repos.sort();
    repos.dedup();
    let mut written = Vec::new();
    for repo in repos {
        let mut entries = Vec::new();
        for row in rows.iter().filter(|r| r.repo == repo) {
            let steps = store
                .steps(&row.repo, row.number, &row.run_id)?
                .into_iter()
                .map(|(step, vendor, _, verdict, _, duration_ms, pass)| (step, vendor, verdict, duration_ms as f64 / 1000.0, pass))
                .collect();
            let run_dir = home.join("runs").join(util::repo_dir_name(&row.repo)).join(format!("issue-{}", row.number)).join(&row.run_id);
            let summary = std::fs::read_to_string(run_dir.join("summary.json")).ok().and_then(|text| serde_json::from_str(&text).ok());
            entries.push(Entry { row: row.clone(), steps, summary });
        }
        entries.sort_by_key(|e| e.row.number);
        let name = repo.rsplit('/').next().unwrap_or(&repo).to_string();
        let file = folder.join(name).join(format!("{date}.md"));
        if let Some(dir) = file.parent() {
            std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        std::fs::write(&file, render(&repo, &date, &entries)).with_context(|| format!("writing {}", file.display()))?;
        written.push(file);
    }
    Ok(written)
}

/// The body of a promotion pull request, from the subjects of what merged.
pub fn promote_body(from: &str, into: &str, subjects: &[String]) -> String {
    let mut out = format!(
        "Promotes `{from}` to `{into}`: {} change{} since the last promotion.\n\n## Changes\n\n",
        subjects.len(),
        if subjects.len() == 1 { "" } else { "s" }
    );
    for subject in subjects {
        out.push_str(&format!("- {}\n", subject.trim()));
    }
    out.push_str(&format!(
        "\nEvery change above went through its own pull request into `{from}`, with verify and review on the merged commit.\n\nOpened by `factory promote`. It is never merged by `factory`: a person approves and merges it.\n"
    ));
    out
}

/// Opens the pull request that promotes the integration branch into `main`,
/// or refreshes it when it is already open. Never merges it.
pub fn promote(repo_dir: &Path) -> Result<bool> {
    let repo_dir = repo_dir.canonicalize().with_context(|| format!("{} does not exist", repo_dir.display()))?;
    let repo = repo_name(&repo_dir)?;
    let home = util::home()?;
    let into = "main";
    let from = {
        let _git = lock::acquire(&home, &format!("git-{}", util::repo_dir_name(&repo)), &|| {})?;
        git::git(&repo_dir, &["fetch", "--quiet", "origin"])?;
        git::git(&repo_dir, &["symbolic-ref", "--short", "refs/remotes/origin/HEAD"])
            .context("could not find the default branch; run `git remote set-head origin --auto`")?
            .trim_start_matches("origin/")
            .to_string()
    };
    if from == into {
        bail!("the default branch of {repo} is already `{into}`, so there is nothing to promote from");
    }
    if git::git(&repo_dir, &["rev-parse", "--verify", "--quiet", &format!("origin/{into}")]).is_err() {
        bail!("{repo} has no `{into}` branch");
    }
    let log = git::git(&repo_dir, &["log", "--first-parent", "--reverse", "--format=%s", &format!("origin/{into}..origin/{from}")])?;
    let subjects: Vec<String> = log.lines().map(str::to_string).filter(|l| !l.trim().is_empty()).collect();
    if subjects.is_empty() {
        println!("nothing to promote: `{into}` already has everything on `{from}`");
        return Ok(true);
    }
    let title = format!("promote: {from} to {into} ({} change{})", subjects.len(), if subjects.len() == 1 { "" } else { "s" });
    let body = promote_body(&from, into, &subjects);
    match github::find_pr(&repo, &from)? {
        Some((number, url)) => {
            github::update_pr(&repo, number, &title, &body)?;
            println!("refreshed {url}: {} change(s)", subjects.len());
        }
        None => {
            let (_, url) = github::open_pr(&repo, into, &from, &title, &body)?;
            println!("opened {url}: {} change(s). A person approves and merges it", subjects.len());
        }
    }
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(number: u64, stage: &str, status: &str, failure: Option<&str>) -> IssueRow {
        IssueRow {
            repo: "o/r".into(),
            number,
            key: format!("k{number}"),
            title: format!("Issue {number}"),
            run_id: "20261124T100000Z".into(),
            stage: stage.into(),
            status: status.into(),
            head_sha: Some("abc123".into()),
            pr_url: (stage != "verify").then(|| format!("https://example.invalid/pull/{number}")),
            failure: failure.map(str::to_string),
            wake_at: None,
            updated_at: "2026-11-24T10:05:00Z".into(),
        }
    }

    #[test]
    fn a_handoff_leads_with_what_needs_a_person() {
        let merged = Entry {
            row: row(7, "merged", "done", None),
            steps: vec![("develop".into(), Some("codex".into()), "replied".into(), 30.0, 0), ("verify".into(), None, "pass".into(), 60.0, 1)],
            summary: Some(Summary { what_changed: "Adds the filter.".into(), how_it_went: "One fix round.".into(), for_a_human: vec!["Check the strikethrough by eye".into()] }),
        };
        let stuck = Entry {
            row: row(8, "verify", "failed", Some("3 fix rounds were used and 'verify' still fails.\nlog\n\nJudgment: escalate. The simulator is broken.")),
            steps: vec![("verify".into(), None, "fail".into(), 5.0, 0)],
            summary: None,
        };
        let text = render("o/r", "2026-11-24", &[merged, stuck]);
        assert!(text.starts_with("# Handoff: o/r, 2026-11-24\n"), "{text}");
        assert!(text.contains("| #7 Issue 7 | Merged | https://example.invalid/pull/7 | 2 | 90 s |"), "{text}");
        assert!(text.contains("| #8 Issue 8 | Needs a person | none | 1 | 5 s |"), "{text}");
        assert!(text.contains("- **#8 Issue 8** stopped at `verify`. 3 fix rounds were used and 'verify' still fails."), "{text}");
        assert!(text.contains("  - Judgment: escalate. The simulator is broken."), "{text}");
        assert!(text.contains("**#7 Issue 7**\n\n- Check the strikethrough by eye"), "{text}");
        assert!(text.contains("| 2 | verify | engine | pass | 60 s |"), "{text}");
        // The order of the sections is what a person needs first.
        let at = |needle: &str| text.find(needle).unwrap();
        assert!(at("## At a glance") < at("## Needs a person") && at("## Needs a person") < at("## To look at") && at("## To look at") < at("## Each issue"));
    }

    #[test]
    fn a_quiet_day_says_so() {
        let text = render("o/r", "2026-11-24", &[Entry { row: row(7, "merged", "done", None), steps: Vec::new(), summary: None }]);
        assert!(text.contains("## Needs a person\n\nNothing.\n"), "{text}");
        assert!(text.contains("## To look at\n\nNothing was flagged.\n"), "{text}");
    }

    #[test]
    fn a_promotion_lists_what_merged() {
        let body = promote_body("dev", "main", &["feat: a (#11)".into(), "fix: b (#14)".into()]);
        assert!(body.starts_with("Promotes `dev` to `main`: 2 changes since the last promotion."), "{body}");
        assert!(body.contains("- feat: a (#11)\n- fix: b (#14)\n"), "{body}");
        assert!(body.contains("never merged by `factory`"), "{body}");
        assert!(promote_body("dev", "main", &["one".into()]).contains(": 1 change since"));
    }
}
